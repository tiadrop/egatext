const fs = require("fs");

const fonts = {
	vga: "./res/VGA-ROM.bmf",
	ega: "./res/EGA-ROM.bin",
};

console.log("Building font(s):", Object.keys(fonts).join(", "))

if (!fs.existsSync("src/fonts")) fs.mkdirSync("src/fonts");

function runlengthEncode(bytes) {
	let prev = -1;
	let runlength = 0;
	const out = [];
	const append = () => {
		if (runlength == 0) return;
		if (runlength == 1) {
			out.push(prev)
		} else {
			out.push([prev, runlength]);
		}
		runlength = 0;
	}
	bytes.forEach(v => {
		if (v !== prev) {
			append();
			prev = v;
		}
		runlength++;
	});
	append();
	return out;
}

Object.entries(fonts).forEach(([name, filename]) => {
	const binaryData = new Uint8Array([...fs.readFileSync(filename)]);
	const rle = runlengthEncode(binaryData);

	const code = `// ** generated by buildfonts.js ** //

import { loadBmfFont, runlengthDecode } from '../bmf.js';
const data = /*#__PURE__*/ runlengthDecode(${JSON.stringify(rle)});
export const _font8 = /*#__PURE__*/ loadBmfFont(data, false);
export const _font9 = /*#__PURE__*/ loadBmfFont(data, true);
`;


	fs.writeFileSync(`src/fonts/${name}.ts`, code)
});

